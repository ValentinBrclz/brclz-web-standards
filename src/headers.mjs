/**
 * Cloudflare Workers Static Assets `_headers` generation and evaluation.
 *
 * Cloudflare applies every matching rule: repeated header names are joined with ", " and
 * `! Name` detaches an inherited header. This module therefore replaces (detach + set) any
 * global header that a narrower rule overrides, rejects ambiguous overlaps, and exposes
 * `resolveHeaders()` so Worker-generated responses (which `_headers` never reaches) and tests
 * can compute the exact header set for a URL.
 * Docs: https://developers.cloudflare.com/workers/static-assets/headers/
 */
import { mergeSettings, resolveSite } from './config.mjs';
import { serializeCsp } from './csp.mjs';
import { checkPattern, compilePattern, resolveRuleHeaders } from './headers-runtime.mjs';

export { applyHeaders, compilePattern } from './headers-runtime.mjs';

/** @typedef {import('./headers-runtime.mjs').CompiledRule} CompiledRule */

export const MAX_RULES = 100;
export const MAX_LINE_LENGTH = 2000;
export const GENERATED_MARKER =
  '# Generated by @valentinbrclz/web-standards from site.config.mjs. Do not edit.';

/** @param {string} name @param {string} value */
function checkLine(name, value) {
  const length = `  ${name}: ${value}`.length;
  if (length > MAX_LINE_LENGTH)
    throw new Error(
      `_headers line for ${name} exceeds Cloudflare's ${MAX_LINE_LENGTH}-character limit (${length})`,
    );
}

/**
 * Builds the ordered rule list for a site.
 * @param {import('./config.mjs').SiteOverrides | Readonly<import('./config.mjs').SiteConfig>} input
 * @returns {CompiledRule[]}
 */
export function buildHeaderRules(input) {
  const site = resolveSite(input);
  const { security, identity } = site;
  const productionHost = new URL(/** @type {string} */ (identity.productionUrl)).hostname;
  const cspName = security.cspReportOnly
    ? 'Content-Security-Policy-Report-Only'
    : 'Content-Security-Policy';

  /** @type {[string, string][]} */
  const global = [];
  for (const [name, value] of Object.entries(security.headers))
    if (value !== null) global.push([name, value]);
  if (security.csp) global.push([cspName, serializeCsp(security.csp)]);
  if (security.hsts) global.push(['Strict-Transport-Security', security.hsts]);
  if (global.some(([name]) => name.toLowerCase() === 'x-robots-tag'))
    throw new Error(
      'security.headers must not set X-Robots-Tag: it would apply to production. Use security.extraRules with allowNoindex for specific paths.',
    );
  const globalNames = new Set(global.map(([name]) => name.toLowerCase()));

  /** @type {CompiledRule[]} */
  const rules = [];
  if (global.length)
    rules.push({ pattern: '/*', detach: [], set: global, source: 'security.headers' });
  if (security.immutableAstroAssets)
    rules.push({
      pattern: '/_astro/*',
      detach: [],
      set: [['Cache-Control', 'public, max-age=31536000, immutable']],
      source: 'security.immutableAstroAssets',
    });
  const preview = identity.previewDomain;
  if (security.previewNoindex && preview) {
    rules.push({
      pattern: `https://:preview.${preview}/*`,
      detach: [],
      set: [['X-Robots-Tag', security.previewRobotsTag]],
      source: 'security.previewNoindex',
    });
    rules.push({
      pattern: `https://${preview}/*`,
      detach: [],
      set: [['X-Robots-Tag', security.previewRobotsTag]],
      source: 'security.previewNoindex',
    });
  }

  security.extraRules.forEach((rule, index) => {
    const source = `security.extraRules[${index}] (${rule.path})`;
    checkPattern(rule.path);
    if (rule.path === '/*')
      throw new Error(`${source}: use security.headers for site-wide headers`);
    const host = rule.path.startsWith('https://')
      ? new URL(rule.path.replace(/:[A-Za-z]\w*/g, 'x').replace('*', 'x')).hostname
      : null;
    const onPreview =
      host !== null && preview !== null && (host === preview || host.endsWith(`.${preview}`));
    /** @type {string[]} */
    const detach = [];
    /** @type {[string, string][]} */
    const set = [];
    for (const [name, value] of Object.entries(rule.headers ?? {})) {
      const lower = name.toLowerCase();
      if (lower === 'x-robots-tag' && value !== null && /\bnoindex\b/i.test(value) && !onPreview) {
        if (host === productionHost || /^https:\/\/[^/]*[:*]/.test(rule.path))
          throw new Error(
            `${source}: X-Robots-Tag noindex on a pattern that covers the whole production site`,
          );
        if (!rule.allowNoindex)
          throw new Error(
            `${source}: X-Robots-Tag noindex outside the preview domain needs "allowNoindex: true" to confirm it is intended for production`,
          );
      }
      if (value === null) {
        detach.push(name);
        continue;
      }
      if (globalNames.has(lower)) detach.push(name);
      set.push([name, value]);
    }
    if (rule.csp !== undefined) {
      if (!security.csp) throw new Error(`${source}: "csp" overrides security.csp, which is null`);
      const merged = mergeSettings(security.csp, rule.csp);
      detach.push(cspName);
      if (merged) set.push([cspName, serializeCsp(merged)]);
    }
    rules.push({ pattern: rule.path, detach, set, source });
  });

  // Checked first: the overlap test below is quadratic in the number of rules.
  if (rules.length > MAX_RULES)
    throw new Error(`Cloudflare allows at most ${MAX_RULES} _headers rules (got ${rules.length})`);
  // Overlapping rules setting the same header would be joined with ", " by Cloudflare. The
  // site-wide rule is exempt: narrower rules detach what they override from it.
  for (let i = 0; i < rules.length; i++) {
    if (rules[i]?.pattern === '/*') continue;
    for (let j = i + 1; j < rules.length; j++) {
      const a = /** @type {CompiledRule} */ (rules[i]);
      const b = /** @type {CompiledRule} */ (rules[j]);
      if (!patternsMayOverlap(a.pattern, b.pattern)) continue;
      for (const [name, value] of b.set) {
        const clash = a.set.find(([n]) => n.toLowerCase() === name.toLowerCase());
        if (
          clash &&
          clash[1] !== value &&
          !b.detach.some((d) => d.toLowerCase() === name.toLowerCase())
        )
          throw new Error(
            `${b.source} and ${a.source} both match some URLs and set ${name}; Cloudflare would join both values. Make the patterns disjoint or detach the header with null.`,
          );
      }
    }
  }

  for (const rule of rules) {
    if (rule.pattern.length > MAX_LINE_LENGTH)
      throw new Error(
        `_headers pattern exceeds ${MAX_LINE_LENGTH} characters: ${rule.pattern.slice(0, 60)}…`,
      );
    for (const [name, value] of rule.set) checkLine(name, value);
  }
  return rules;
}

/**
 * Conservative overlap test: true unless the two patterns provably match disjoint URL sets.
 * @param {string} a @param {string} b
 */
export function patternsMayOverlap(a, b) {
  /** @param {string} p */
  const sample = (p) => p.replace(/:[A-Za-z]\w*/g, 'x').replace('*', 'x/y');
  const absA = a.startsWith('https://');
  const absB = b.startsWith('https://');
  if (absA && absB) {
    const hostA = new URL(sample(a)).hostname;
    const hostB = new URL(sample(b)).hostname;
    if (
      !/[:*]/.test(a.split('/')[2] ?? '') &&
      !/[:*]/.test(b.split('/')[2] ?? '') &&
      hostA !== hostB
    )
      return false;
  }
  /** @param {string} p */
  const pathOf = (p) =>
    p.startsWith('https://')
      ? p.slice(p.indexOf('/', 8) === -1 ? p.length : p.indexOf('/', 8)) || '/'
      : p;
  const pa = pathOf(a);
  const pb = pathOf(b);
  /** @param {string} p */
  const prefix = (p) => p.split(/[*:]/)[0] ?? '';
  const wildA = /[*:]/.test(pa);
  const wildB = /[*:]/.test(pb);
  if (!wildA && !wildB) return pa.toLowerCase() === pb.toLowerCase();
  const fa = prefix(pa).toLowerCase();
  const fb = prefix(pb).toLowerCase();
  if (!wildA) return compilePattern(pb)(`https://x${pa}`) || (absB && !absA);
  if (!wildB) return compilePattern(pa)(`https://x${pb}`) || (absA && !absB);
  return fa.startsWith(fb) || fb.startsWith(fa);
}

/**
 * Serialises rules to `_headers` text (deterministic).
 * @param {CompiledRule[]} rules
 */
export function serializeHeaderRules(rules) {
  const blocks = rules.map((rule) =>
    [
      rule.pattern,
      ...rule.detach.map((name) => `  ! ${name}`),
      ...rule.set.map(([name, value]) => `  ${name}: ${value}`),
    ].join('\n'),
  );
  return `${[GENERATED_MARKER, ...blocks].join('\n\n')}\n`;
}

/**
 * Generates the complete `_headers` file for a site.
 * @param {import('./config.mjs').SiteOverrides | Readonly<import('./config.mjs').SiteConfig>} site
 */
export function generateHeaders(site) {
  return serializeHeaderRules(buildHeaderRules(site));
}

/**
 * Parses an existing `_headers` file (for migration comparisons and drift checks).
 * @param {string} text
 * @returns {CompiledRule[]}
 */
export function parseHeadersFile(text) {
  /** @type {CompiledRule[]} */
  const rules = [];
  /** @type {CompiledRule | undefined} */
  let current;
  for (const [index, raw] of text.split(/\r?\n/).entries()) {
    if (!raw.trim() || raw.trim().startsWith('#')) continue;
    if (!/^\s/.test(raw)) {
      checkPattern(raw.trim());
      current = { pattern: raw.trim(), detach: [], set: [], source: `line ${index + 1}` };
      rules.push(current);
      continue;
    }
    if (!current) throw new Error(`_headers line ${index + 1}: header before any URL pattern`);
    const line = raw.trim();
    if (line.startsWith('!')) current.detach.push(line.slice(1).trim());
    else {
      const colon = line.indexOf(':');
      if (colon < 1) throw new Error(`_headers line ${index + 1}: expected "Name: value"`);
      current.set.push([line.slice(0, colon).trim(), line.slice(colon + 1).trim()]);
    }
  }
  return rules;
}

/**
 * Emulates Cloudflare's documented evaluation of `_headers` for one URL, from compiled rules or
 * from a site (which is compiled first). Workers should precompile with `brclz
 * generate-header-rules` and call `applyHeaders()` instead. Keys are returned as written.
 * @param {CompiledRule[] | import('./config.mjs').SiteOverrides | Readonly<import('./config.mjs').SiteConfig>} rulesOrSite
 * @param {string | URL} url
 * @returns {Record<string, string>}
 */
export function resolveHeaders(rulesOrSite, url) {
  return resolveRuleHeaders(
    Array.isArray(rulesOrSite) ? rulesOrSite : buildHeaderRules(rulesOrSite),
    url,
  );
}

/**
 * Serialises compiled rules as JSON for a Worker (`source` is dropped: it only serves build errors).
 * @param {CompiledRule[]} rules
 */
export function serializeRulesJson(rules) {
  return `${JSON.stringify(rules.map(({ pattern, detach, set }) => ({ pattern, detach, set })))}\n`;
}
