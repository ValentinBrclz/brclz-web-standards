// End-to-end smoke test: packs this repository, creates a site with `brclz init` (all features)
// using the tarball, runs its own checks and Playwright/axe tests, builds it, runs the CLI checks, validates the Wrangler file
// with `wrangler deploy --dry-run` and checks real responses from `wrangler dev` (local workerd).
// Needs network access to the npm registry. Nothing is deployed.
import { execFileSync, spawn, spawnSync } from 'node:child_process';
import { mkdir, mkdtemp, readdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { request } from 'node:http';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { setTimeout as sleep } from 'node:timers/promises';

const root = resolve(import.meta.dirname, '..');
const keep = process.argv.includes('--keep');
const work = await mkdtemp(join(tmpdir(), 'web-standards-smoke-'));
const project = join(work, 'site');
const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
const failures = [];

/** @param {string} cmd @param {string[]} args @param {string} [cwd] */
function run(cmd, args, cwd = project) {
  console.log(`$ ${cmd} ${args.join(' ')}`);
  return execFileSync(cmd, args, {
    cwd,
    stdio: ['ignore', 'pipe', 'inherit'],
    encoding: 'utf8',
    env: { ...process.env, ASTRO_TELEMETRY_DISABLED: '1', WRANGLER_SEND_METRICS: 'false' },
  });
}
/** Stops `npx wrangler dev` and its workerd children (spawned detached, in their own group). */
function stop(/** @type {import('node:child_process').ChildProcess} */ child) {
  try {
    if (child.pid) process.kill(-child.pid, 'SIGTERM');
  } catch {
    child.kill('SIGTERM');
  }
}
/** @param {boolean} ok @param {string} message */
function expect(ok, message) {
  console.log(`${ok ? 'ok  ' : 'FAIL'} ${message}`);
  if (!ok) failures.push(message);
}

/** @param {string} title @param {string} body */
const page = (title, body, robots = 'index, follow') => `---
import Layout from '../layouts/BaseLayout.astro';
---
<Layout title="${title}" description="${title} description for the smoke test." robots="${robots}">
  <main id="main">
    <h1>${title}</h1>
    ${body}
  </main>
  <style>h1 { color: rebeccapurple; }</style>
  <script>document.documentElement.dataset.ready = 'true';</script>
</Layout>
`;

try {
  const pack = JSON.parse(run(npm, ['pack', '--json', '--pack-destination', work], root));
  const tarball = join(work, pack[0].filename);
  // The documented new-project path: `brclz init` with every optional feature, real install.
  run(
    process.execPath,
    [
      join(root, 'bin/brclz.mjs'),
      'init',
      project,
      '--name',
      'Smoke site',
      '--url',
      'https://example.com',
      '--features',
      'all',
      '--standards',
      `file:${tarball}`,
    ],
    work,
  );
  expect(
    (await readFile(join(project, '.claude/rules/web-standards/web-standards.md'), 'utf8')).length >
      0,
    'init installed the Claude Code rules',
  );
  run(npm, ['run', 'check']);
  await writeFile(
    join(project, 'src/pages/index.astro'),
    page(
      'Home',
      '<a href="/about">About</a><button type="button" data-analytics-accept>Accept analytics</button>',
    ),
  );
  await writeFile(join(project, 'src/pages/about.astro'), page('About', '<p>About page.</p>'));
  await mkdir(join(project, 'public'), { recursive: true });
  await writeFile(join(project, 'public/_redirects'), '/old-about /about 301\n');

  run(npm, ['run', 'build']);
  const headers = await readFile(join(project, 'dist/_headers'), 'utf8');
  expect(
    headers.startsWith('# Generated by @valentinbrclz/web-standards'),
    'dist/_headers is generated',
  );
  run('npx', ['--no-install', 'brclz', 'check', '--strict']);
  run('npx', ['--no-install', 'brclz', 'audit-dist', '--strict']);
  // The generated site resolves the shared commitlint configuration from the packed tarball.
  for (const { message, ok } of [
    { message: 'feat(site): add search', ok: true },
    { message: 'Added stuff.', ok: false },
  ]) {
    const result = spawnSync('npx', ['--no-install', 'commitlint'], {
      cwd: project,
      input: message,
      encoding: 'utf8',
    });
    expect(
      (result.status === 0) === ok,
      `commitlint ${ok ? 'accepts' : 'rejects'} "${message}"${result.status === (ok ? 0 : 1) ? '' : `: ${result.stderr || result.stdout}`}`,
    );
  }
  // The site pins its own @playwright/test (templates/astro-static/package.json), which can differ
  // from this repository's Playwright: fetch the Chromium revision that version expects.
  try {
    run('npx', ['--no-install', 'playwright', 'install', 'chromium']);
  } catch {
    console.log('warn browser download failed; the e2e run uses whatever Chromium is installed');
  }
  run(npm, ['run', 'test:e2e']);
  const index = await readFile(join(project, 'dist/index.html'), 'utf8');
  expect(
    !/<script>(?!\s*<\/script>)/.test(index) && !/<style>/.test(index),
    'strict CSP: Astro emitted no inline <script>/<style> (baseAstroConfig)',
  );
  expect(!index.includes('analytics-config'), 'analytics disabled: no analytics markup');
  const dry = run('npx', ['wrangler', 'deploy', '--dry-run', '--outdir', join(work, 'dry-run')]);
  expect(/dry-run: exiting now/i.test(dry), 'wrangler deploy --dry-run accepts wrangler.toml');

  // Real responses from the local Workers runtime.
  const port = 8900 + Math.floor(Math.random() * 90);
  const dev = spawn('npx', ['wrangler', 'dev', '--port', String(port), '--log-level', 'warn'], {
    cwd: project,
    stdio: 'ignore',
    detached: true,
    env: { ...process.env, WRANGLER_SEND_METRICS: 'false' },
  });
  /** @param {string} path @param {string} [host] */
  const get = (path, host) =>
    new Promise((resolvePromise, reject) => {
      const req = request(
        { host: '127.0.0.1', port, path, headers: host ? { host } : {} },
        (res) => {
          res.resume();
          res.on('end', () => resolvePromise(res));
        },
      );
      req.on('error', reject);
      req.end();
    });
  try {
    let ready = false;
    for (let i = 0; i < 60 && !ready; i++) {
      ready = await get('/').then(
        () => true,
        () => false,
      );
      if (!ready) await sleep(1000);
    }
    expect(ready, 'wrangler dev started');
    if (ready) {
      const home = /** @type {import('node:http').IncomingMessage} */ (await get('/'));
      expect(home.statusCode === 200, 'GET / is 200');
      expect(
        String(home.headers['content-security-policy']).includes("default-src 'self'"),
        'GET / sends the CSP',
      );
      expect(
        home.headers['x-robots-tag'] === undefined,
        'GET / (production host) has no X-Robots-Tag',
      );
      const about = /** @type {import('node:http').IncomingMessage} */ (await get('/about'));
      expect(about.statusCode === 200, 'GET /about is 200 (file format + drop-trailing-slash)');
      const slash = /** @type {import('node:http').IncomingMessage} */ (await get('/about/'));
      expect(
        [307, 308].includes(slash.statusCode ?? 0) && slash.headers.location === '/about',
        'GET /about/ redirects to /about',
      );
      const old = /** @type {import('node:http').IncomingMessage} */ (await get('/old-about'));
      expect(
        old.statusCode === 301 && old.headers.location === '/about',
        '_redirects: /old-about -> /about (301)',
      );
      const missing = /** @type {import('node:http').IncomingMessage} */ (
        await get('/does-not-exist')
      );
      expect(missing.statusCode === 404, 'unknown path returns the 404 page with status 404');
      const asset = (await readdir(join(project, 'dist/_astro'))).find(
        (f) => f.endsWith('.css') || f.endsWith('.js'),
      );
      if (asset) {
        const res = /** @type {import('node:http').IncomingMessage} */ (
          await get(`/_astro/${asset}`)
        );
        expect(
          String(res.headers['cache-control']).includes('immutable'),
          '/_astro assets are immutable',
        );
      }
      const preview = /** @type {import('node:http').IncomingMessage} */ (
        await get('/', 'feature-x.dev.example.com')
      );
      if (preview.headers['x-robots-tag'] !== undefined)
        expect(
          preview.headers['x-robots-tag'] === 'noindex',
          'Preview host gets X-Robots-Tag: noindex',
        );
      else
        console.log(
          'skip Preview host rule: wrangler dev ignored the Host header (verify on a real Preview deployment)',
        );
    }
  } finally {
    stop(dev);
  }

  // Second build with PostHog enabled: the CSP must allow its host and no inline code may appear.
  await rename(join(project, 'site.config.mjs'), join(project, 'site.config.base.mjs'));
  await writeFile(
    join(project, 'site.config.mjs'),
    `import base from './site.config.base.mjs';
export default {
  ...base,
  security: { ...base.security, csp: { ...base.security.csp, 'connect-src': ["'self'", 'https://eu.i.posthog.com'] } },
  analytics: { posthog: { enabled: true, projectKey: 'phc_smoketest', events: ['download_click'] } },
};
`,
  );
  run(npm, ['run', 'build']);
  run('npx', ['--no-install', 'brclz', 'audit-dist']);
  const withAnalytics = await readFile(join(project, 'dist/index.html'), 'utf8');
  expect(
    withAnalytics.includes('id="analytics-config"'),
    'analytics enabled: JSON config block rendered',
  );
  expect(
    withAnalytics.includes('"consent":"opt-in"'),
    'analytics config carries the opt-in consent model',
  );
  await browserConsentCheck();
} catch (error) {
  failures.push(error instanceof Error ? error.message : String(error));
  console.error(error);
} finally {
  if (keep) console.log(`kept ${work}`);
  else await rm(work, { recursive: true, force: true, maxRetries: 5, retryDelay: 500 });
}

/**
 * Serves the PostHog build with `wrangler dev` and opens it in Chromium under the production
 * hostname (host-resolver mapping): no PostHog request before consent, requests after it.
 * Skipped when Playwright is not installed.
 */
async function browserConsentCheck() {
  /** @type {any} */
  let playwright;
  try {
    playwright = createRequire(import.meta.url)('playwright');
  } catch {
    console.log('skip browser consent check: playwright is not installed');
    return;
  }
  const port = 8990 + Math.floor(Math.random() * 9);
  const dev = spawn('npx', ['wrangler', 'dev', '--port', String(port), '--log-level', 'warn'], {
    cwd: project,
    stdio: 'ignore',
    detached: true,
    env: { ...process.env, WRANGLER_SEND_METRICS: 'false' },
  });
  const browser = await playwright.chromium.launch({
    args: [`--host-resolver-rules=MAP example.com 127.0.0.1`],
    // Set when the installed Chromium belongs to another Playwright version.
    executablePath: process.env.SMOKE_CHROMIUM_PATH || undefined,
  });
  try {
    /** @type {string[]} */
    const posthogRequests = [];
    // posthog-js drops events from automated browsers (navigator.webdriver, HeadlessChrome).
    const page = await browser.newPage({
      userAgent:
        'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0.0.0 Safari/537.36',
    });
    await page.addInitScript(() =>
      Object.defineProperty(navigator, 'webdriver', { get: () => false }),
    );
    /** @type {string[]} */
    const cspErrors = [];
    page.on('console', (/** @type {any} */ msg) => {
      if (/Content Security Policy/i.test(msg.text())) cspErrors.push(msg.text());
    });
    await page.route('https://eu.i.posthog.com/**', (/** @type {any} */ route) => {
      posthogRequests.push(route.request().url());
      return route.fulfill({ status: 200, contentType: 'application/json', body: '{"status":1}' });
    });
    let loaded = false;
    for (let i = 0; i < 60 && !loaded; i++) {
      loaded = await page.goto(`http://example.com:${port}/`).then(
        (/** @type {any} */ res) => res?.status() === 200,
        () => false,
      );
      if (!loaded) await sleep(1000);
    }
    expect(loaded, 'browser: page served by wrangler dev under the production hostname');
    if (!loaded) return;
    await page.waitForTimeout(1500);
    expect(posthogRequests.length === 0, 'browser: no PostHog request before consent');
    await page.click('[data-analytics-accept]');
    for (let i = 0; i < 20 && !posthogRequests.length; i++) await page.waitForTimeout(500);
    await page.evaluate(() => window.dispatchEvent(new Event('pagehide')));
    for (let i = 0; i < 20 && !posthogRequests.length; i++) await page.waitForTimeout(500);
    expect(posthogRequests.length > 0, 'browser: PostHog sends events after consent');
    expect(
      posthogRequests.every((u) => !u.includes('/static/') && !u.includes('/array/')),
      'browser: no remote PostHog scripts loaded',
    );
    const stored = await page.evaluate(() =>
      localStorage.getItem('web-standards:analytics-consent'),
    );
    expect(Boolean(stored?.includes('granted')), 'browser: consent decision stored');
    expect(
      cspErrors.length === 0,
      `browser: no CSP violations${cspErrors.length ? ` (${cspErrors[0]})` : ''}`,
    );
  } finally {
    await browser.close();
    stop(dev);
  }
}

if (failures.length) {
  console.error(`\n${failures.length} smoke check(s) failed:\n- ${failures.join('\n- ')}`);
  process.exitCode = 1;
} else console.log('\nSmoke test passed');
