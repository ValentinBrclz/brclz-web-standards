#!/usr/bin/env node
import { spawnSync } from 'node:child_process';
import { access, cp, mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';
import { findAstroConfigConflicts } from '../src/astro.mjs';
import { defineSite, lintSite } from '../src/config.mjs';
import {
  buildHeaderRules,
  GENERATED_MARKER,
  generateHeaders,
  serializeRulesJson,
} from '../src/headers.mjs';
import { alignCompatibilityDate, FEATURES, initProject } from '../src/init.mjs';
import { checkRedirects } from '../src/redirects.mjs';
import { auditDist } from '../src/seo.mjs';
import { findSiteFile, SITE_JSON, syncSiteFile } from '../src/site-file.mjs';
import {
  checkWranglerConfig,
  generateStaticWrangler,
  readWranglerConfig,
} from '../src/wrangler.mjs';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const USAGE = `Usage: brclz <command> [options]

Commands:
  init <dir>          Create a new Astro site wired to the standards (see init options)
  check               Validate site.config.mjs, generated headers, _redirects and Wrangler config
  print-config        Print the resolved configuration (defaults + overrides) as JSON
  generate-headers    Write dist/_headers (run after the build)
  generate-header-rules  Write the compiled header rules as JSON for a Worker (--check only compares)
  sync-site-file      Write site.yaml as site.generated.json for site.config.mjs (--check only compares)
  validate-redirects  Validate a _redirects file
  check-wrangler      Compare the project's Wrangler file with site.config.mjs
  generate-wrangler   Write a Wrangler JSON file for a purely static Worker (never deploys)
  audit-dist          Audit built HTML, robots.txt, sitemap and llms.txt
  install-claude      Copy Claude Code rules and skills into a project

Options:
  --site <file>       Site configuration (default: ./site.config.mjs)
  --out <file>        Output file (generate-headers: ./dist/_headers; generate-header-rules:
                      ./.generated/header-rules.json; generate-wrangler: ./.generated/wrangler.json)
  --file <file>       _redirects file (default: ./dist/_redirects, else ./public/_redirects)
  --config <file>     Wrangler file (default: wrangler.toml / wrangler.jsonc / wrangler.json)
  --dist <dir>        Build output (default: ./dist)
  --target <dir>      install-claude destination (default: .)
  --from <file>       sync-site-file source (default: site.yaml, else site.yml)
  --to <file>         sync-site-file output (default: ./site.generated.json)
  --check             sync-site-file, generate-header-rules: fail when the output is missing or stale
  --strict            Treat warnings as errors
  --force             Overwrite files that were not generated by this tool
  -h, --help          Show this help
  -v, --version       Print the package version

init options:
  --name <name>            Site name (required)
  --url <origin>           Production origin, e.g. https://www.example.com (required)
  --preview-domain <host>  Default: dev.<host without www>
  --worker-name <name>     Default: reversed host without www (example.org -> org-example)
  --language <tag>         Default: fr-CH
  --features <list>        Comma-separated: ${Object.keys(FEATURES).join(', ')}, or "all"
  --standards <spec>       npm spec of this package (default: this version's git tag)
  --skip-install           Do not run npm install
  --skip-claude            Do not install the Claude Code rules and skills`;

class UsageError extends Error {}

/** @param {string} path */
const exists = (path) =>
  access(path).then(
    () => true,
    () => false,
  );

let parsed;
try {
  parsed = parseArgs({
    allowPositionals: true,
    options: {
      site: { type: 'string', default: './site.config.mjs' },
      out: { type: 'string' },
      file: { type: 'string' },
      redirects: { type: 'string' },
      config: { type: 'string' },
      dist: { type: 'string', default: './dist' },
      target: { type: 'string', default: '.' },
      from: { type: 'string' },
      to: { type: 'string' },
      check: { type: 'boolean', default: false },
      name: { type: 'string' },
      url: { type: 'string' },
      'preview-domain': { type: 'string' },
      'worker-name': { type: 'string' },
      language: { type: 'string' },
      features: { type: 'string' },
      standards: { type: 'string' },
      'skip-install': { type: 'boolean', default: false },
      'skip-claude': { type: 'boolean', default: false },
      strict: { type: 'boolean', default: false },
      force: { type: 'boolean', default: false },
      help: { type: 'boolean', short: 'h', default: false },
      version: { type: 'boolean', short: 'v', default: false },
    },
  });
} catch (error) {
  console.error(`${/** @type {Error} */ (error).message}\n\n${USAGE}`);
  process.exit(2);
}
const { values: opts, positionals } = parsed;
const [command, ...extra] = positionals;
/** @type {string[]} */
const warnings = [];

async function loadSite() {
  const path = resolve(/** @type {string} */ (opts.site));
  if (!(await exists(path)))
    throw new UsageError(`Site configuration not found: ${path} (pass --site <file>)`);
  const module = await import(pathToFileURL(path).href);
  if (module.default === undefined) throw new Error(`${path} has no default export`);
  const site = defineSite(module.default);
  warnings.push(...lintSite(site));
  return site;
}

async function findWranglerConfig() {
  if (opts.config) return resolve(opts.config);
  const found = [];
  for (const name of ['wrangler.toml', 'wrangler.jsonc', 'wrangler.json'])
    if (await exists(resolve(name))) found.push(resolve(name));
  if (found.length > 1)
    throw new Error(
      `Several Wrangler files found (${found.map((f) => relative('.', f)).join(', ')}); keep exactly one`,
    );
  return found[0];
}

async function findRedirects() {
  const explicit = opts.file ?? opts.redirects;
  if (explicit) return resolve(explicit);
  for (const candidate of [
    join(/** @type {string} */ (opts.dist), '_redirects'),
    './public/_redirects',
  ])
    if (await exists(resolve(candidate))) return resolve(candidate);
  return undefined;
}

/**
 * When the project authors its domain in site.yaml, site.config.mjs imports a JSON copy
 * (Workers cannot read YAML). The copy must match the site file.
 */
async function siteFileReport() {
  const source = findSiteFile();
  if (!source || !(await exists(resolve(SITE_JSON)))) return;
  const result = syncSiteFile({ from: source, check: true });
  if (result.status === 'stale')
    throw new Error(
      `${SITE_JSON} is out of date with ${source}: run "npx brclz sync-site-file" and commit the result`,
    );
  console.log(`Site file: ${SITE_JSON} matches ${source}`);
}

/**
 * The origin, trailing-slash policy and build format live in site.config.mjs only;
 * astro.config.mjs gets them from baseAstroConfig(). A second copy would win silently.
 */
async function astroConfigReport() {
  for (const name of [
    'astro.config.mjs',
    'astro.config.ts',
    'astro.config.js',
    'astro.config.mts',
  ]) {
    const path = resolve(name);
    if (!(await exists(path))) continue;
    const conflicts = findAstroConfigConflicts(await readFile(path, 'utf8'));
    if (conflicts.length)
      throw new Error(
        `${name} repeats settings that site.config.mjs owns (two sources of truth):\n${conflicts
          .map((c) => `- ${name}:${c.line} sets "${c.key}"`)
          .join(
            '\n',
          )}\nRemove them: baseAstroConfig(defineSite(siteOverrides)) derives site, trailingSlash and build.format. If the domain is authored in another file (for example site.yaml), read it from site.config.mjs with readSiteFile().`,
      );
    console.log(`Astro: ${name} takes its site settings from site.config.mjs`);
    return;
  }
}

/** @param {import('../src/config.mjs').SiteConfig} site @param {string} path */
async function redirectsReport(site, path) {
  const report = checkRedirects(await readFile(path, 'utf8'), {
    trailingSlash: site.astro.trailingSlash,
    productionUrl: /** @type {string} */ (site.identity.productionUrl),
  });
  warnings.push(...report.warnings.map((w) => `${relative('.', path)} ${w}`));
  return report;
}

/** @param {import('../src/config.mjs').SiteConfig} site @param {string} path */
async function wranglerReport(site, path) {
  const result = checkWranglerConfig(site, await readWranglerConfig(path), {
    configDir: dirname(path),
    projectDir: process.cwd(),
  });
  warnings.push(...result.warnings.map((w) => `${relative('.', path)}: ${w}`));
  if (result.errors.length)
    throw new Error(
      `${relative('.', path)} disagrees with the site configuration:\n- ${result.errors.join('\n- ')}`,
    );
}

async function installClaude(target = /** @type {string} */ (opts.target)) {
  const dest = resolve(target);
  const source = join(packageRoot, 'claude');
  /** @type {[string, string][]} */
  const files = [['settings.json', '.claude/settings.json']];
  for (const folder of ['rules', 'skills']) {
    /** @param {string} path */
    const visit = async (path) => {
      for (const entry of await readdir(join(source, path), { withFileTypes: true })) {
        const sub = join(path, entry.name);
        if (entry.isDirectory()) await visit(sub);
        else
          files.push([
            sub,
            join(
              '.claude',
              folder === 'rules' ? sub.replace(/^rules/, 'rules/web-standards') : sub,
            ),
          ]);
      }
    };
    await visit(folder);
  }
  const skipped = [];
  const written = [];
  for (const [from, to] of files) {
    const target = join(dest, to);
    if ((await exists(target)) && !opts.force) {
      skipped.push(to);
      continue;
    }
    await mkdir(dirname(target), { recursive: true });
    await cp(join(source, from), target, { force: true });
    written.push(to);
  }
  for (const name of ['CLAUDE.md', 'AGENTS.md']) {
    if (!(await exists(join(dest, name)))) {
      await cp(join(source, name), join(dest, name));
      written.push(name);
    } else skipped.push(name);
  }
  console.log(`Installed ${written.length} file(s) into ${dest}`);
  for (const file of written) console.log(`  + ${file}`);
  if (skipped.length) {
    console.log('Kept existing files (merge manually; --force overwrites .claude/ files only):');
    for (const file of skipped) console.log(`  = ${file}`);
  }
}

async function main() {
  if (opts.version) {
    console.log(JSON.parse(await readFile(join(packageRoot, 'package.json'), 'utf8')).version);
    return;
  }
  if (opts.help || !command) {
    console.log(USAGE);
    if (!command && !opts.help) process.exitCode = 2;
    return;
  }
  if (extra.length > (command === 'init' ? 1 : 0))
    throw new UsageError(`Unexpected argument(s): ${extra.join(' ')}`);
  switch (command) {
    case 'check': {
      const site = await loadSite();
      generateHeaders(site);
      const redirects = await findRedirects();
      if (redirects && (await exists(redirects))) {
        const report = await redirectsReport(site, redirects);
        console.log(
          `Redirects: ${report.static} static, ${report.dynamic} dynamic (${relative('.', redirects)})`,
        );
      } else if (opts.file ?? opts.redirects)
        throw new UsageError(`Redirects file not found: ${redirects}`);
      const wrangler = await findWranglerConfig();
      if (wrangler) {
        if (!(await exists(wrangler))) throw new UsageError(`Wrangler file not found: ${wrangler}`);
        await wranglerReport(site, wrangler);
        console.log(`Wrangler: ${relative('.', wrangler)} matches the site configuration`);
      }
      await siteFileReport();
      await astroConfigReport();
      console.log(`Valid site configuration: ${site.identity.productionUrl}`);
      break;
    }
    case 'print-config':
      console.log(JSON.stringify(await loadSite(), null, 2));
      break;
    case 'sync-site-file': {
      const result = syncSiteFile({ from: opts.from, to: opts.to, check: opts.check });
      if (result.status === 'stale' || result.status === 'missing') {
        console.error(
          `${result.to} is ${result.status === 'missing' ? 'missing' : 'out of date'} with ${result.from}: run "npx brclz sync-site-file" and commit the result`,
        );
        process.exitCode = 1;
      } else
        console.log(
          result.status === 'written'
            ? `Wrote ${result.to} from ${result.from}`
            : `${result.to} is up to date with ${result.from}`,
        );
      break;
    }
    case 'generate-headers': {
      const site = await loadSite();
      const out = resolve(opts.out ?? join(/** @type {string} */ (opts.dist), '_headers'));
      if ((await exists(out)) && !opts.force) {
        const current = await readFile(out, 'utf8');
        if (!current.startsWith(GENERATED_MARKER))
          throw new Error(
            `${relative('.', out)} already exists and was not generated by brclz (probably copied from public/_headers). Move its rules into site.config.mjs (security.extraRules) and delete public/_headers, or pass --force to overwrite it.`,
          );
      }
      await mkdir(dirname(out), { recursive: true });
      await writeFile(out, generateHeaders(site), 'utf8');
      console.log(`Generated ${relative('.', out)}`);
      break;
    }
    case 'generate-header-rules': {
      const site = await loadSite();
      const out = resolve(opts.out ?? './.generated/header-rules.json');
      const json = serializeRulesJson(buildHeaderRules(site));
      if (opts.check) {
        const current = (await exists(out)) ? await readFile(out, 'utf8') : null;
        if (current === json) console.log(`${relative('.', out)} is up to date`);
        else {
          console.error(
            `${relative('.', out)} is ${current === null ? 'missing' : 'out of date'}: run "npx brclz generate-header-rules"`,
          );
          process.exitCode = 1;
        }
        break;
      }
      await mkdir(dirname(out), { recursive: true });
      await writeFile(out, json, 'utf8');
      console.log(`Generated ${relative('.', out)} (import it in the Worker for applyHeaders())`);
      break;
    }
    case 'validate-redirects': {
      const site = await loadSite();
      const path = await findRedirects();
      if (!path || !(await exists(path)))
        throw new UsageError('No _redirects file found (pass --file <file>)');
      const report = await redirectsReport(site, path);
      console.log(
        `Validated ${report.redirects.length} redirects (${report.static} static, ${report.dynamic} dynamic)`,
      );
      break;
    }
    case 'check-wrangler': {
      const site = await loadSite();
      const path = await findWranglerConfig();
      if (!path || !(await exists(path)))
        throw new UsageError('No Wrangler file found (pass --config <file>)');
      await wranglerReport(site, path);
      console.log(`${relative('.', path)} matches the site configuration`);
      break;
    }
    case 'generate-wrangler': {
      const site = await loadSite();
      const out = resolve(opts.out ?? './.generated/wrangler.json');
      if ((await exists(out)) && !opts.force && !out.includes(`${join('.generated', '')}`))
        throw new Error(
          `${relative('.', out)} exists; pass --force to overwrite a project-owned Wrangler file`,
        );
      const config = generateStaticWrangler(site, {
        configDir: dirname(out),
        projectDir: process.cwd(),
      });
      await mkdir(dirname(out), { recursive: true });
      await writeFile(out, `${JSON.stringify(config, null, 2)}\n`, 'utf8');
      console.log(
        `Generated ${relative('.', out)} (not deployed; review it before use with wrangler --config)`,
      );
      break;
    }
    case 'audit-dist': {
      const site = await loadSite();
      const dist = resolve(/** @type {string} */ (opts.dist));
      if (!(await exists(dist)))
        throw new UsageError(`Build output not found: ${dist} (run the build first)`);
      const report = await auditDist(dist, site);
      warnings.push(...report.warnings);
      if (report.errors.length)
        throw new Error(`SEO audit failed:\n- ${report.errors.join('\n- ')}`);
      console.log(
        `SEO audit passed (${report.htmlPages} HTML pages, ${report.indexablePages} indexable)`,
      );
      break;
    }
    case 'install-claude':
      await installClaude();
      break;
    case 'init': {
      const [directory] = extra;
      if (!directory || !opts.name || !opts.url)
        throw new UsageError(
          'init needs a directory, --name and --url, e.g. brclz init my-site --name "My site" --url https://www.example.com',
        );
      const features =
        opts.features === 'all'
          ? Object.keys(FEATURES)
          : (opts.features ?? '')
              .split(',')
              .map((f) => f.trim())
              .filter(Boolean);
      const result = await initProject({
        directory,
        name: opts.name,
        url: opts.url,
        previewDomain: opts['preview-domain'],
        workerName: opts['worker-name'],
        language: opts.language,
        features,
        standardsSpec: opts.standards,
      });
      console.log(`Created ${result.directory} (${result.files.length} files)`);
      console.log(
        `  production ${result.url}, previews *.${result.previewDomain}, worker ${result.workerName}`,
      );
      console.log(
        `  features: ${result.features.length ? result.features.join(', ') : 'core only'}`,
      );
      if (!opts['skip-claude']) await installClaude(result.directory);
      if (!opts['skip-install']) {
        const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
        /** @param {string[]} args */
        const run = (args) => {
          console.log(`$ npm ${args.join(' ')}`);
          const child = spawnSync(npm, args, { cwd: result.directory, stdio: 'inherit' });
          if (child.status !== 0)
            throw new Error(`npm ${args.join(' ')} failed in ${result.directory}`);
        };
        run(['install', '--no-audit', '--no-fund']);
        // A Wrangler release older than today cannot run today's compatibility date locally.
        const aligned = await alignCompatibilityDate(result.directory, result.compatibilityDate);
        if (!aligned)
          warnings.push(
            `could not read the installed workerd version; check compatibility_date (${result.compatibilityDate}) in wrangler.toml`,
          );
        else if (aligned.changed)
          console.log(
            `  compatibility date ${aligned.date} (newest supported by the installed Wrangler)`,
          );
        run(['exec', '--', 'biome', 'check', '--write', '.']);
      }
      console.log(`\nNext: cd ${directory} && npx playwright install chromium && npm run verify`);
      break;
    }
    default:
      throw new UsageError(`Unknown command "${command}"`);
  }
}

try {
  await main();
  if (warnings.length) {
    console.warn(`${warnings.length} warning(s):\n- ${warnings.join('\n- ')}`);
    if (opts.strict) {
      console.error('Failing because of --strict');
      process.exitCode = 1;
    }
  }
} catch (error) {
  if (warnings.length) console.warn(`warning(s):\n- ${warnings.join('\n- ')}`);
  console.error(error instanceof Error ? error.message : String(error));
  if (error instanceof UsageError) console.error('\nRun "brclz --help" for usage.');
  process.exitCode = error instanceof UsageError ? 2 : 1;
}
