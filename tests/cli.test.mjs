import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { after, describe, it } from 'node:test';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const bin = join(root, 'bin/brclz.mjs');
const dirs = [];
after(() => Promise.all(dirs.map((d) => rm(d, { recursive: true, force: true }))));

/** @param {string[]} args @param {string} cwd */
const cli = (args, cwd) => spawnSync(process.execPath, [bin, ...args], { cwd, encoding: 'utf8' });

/** A project created by `brclz init` without installation. @param {string[]} args */
async function project(...args) {
  const parent = await mkdtemp(join(tmpdir(), 'ws-cli-'));
  dirs.push(parent);
  const dir = join(parent, 'site');
  const result = cli(
    [
      'init',
      dir,
      '--name',
      'Example',
      '--url',
      'https://www.example.com',
      '--skip-install',
      '--skip-claude',
      ...args,
    ],
    parent,
  );
  assert.equal(result.status, 0, result.stderr);
  return dir;
}

describe('cli', () => {
  it('prints help and version, and rejects unknown commands and flags', async () => {
    assert.match(cli(['--help'], root).stdout, /Usage: brclz <command>/);
    assert.equal(
      cli(['--version'], root).stdout.trim(),
      JSON.parse(await readFile(join(root, 'package.json'), 'utf8')).version,
    );
    const unknown = cli(['frobnicate'], root);
    assert.equal(unknown.status, 2);
    assert.match(unknown.stderr, /Unknown command "frobnicate"/);
    const flag = cli(['check', '--sitee', 'x'], root);
    assert.equal(flag.status, 2);
    assert.match(flag.stderr, /Unknown option '--sitee'/);
    assert.equal(cli([], root).status, 2);
  });
  it('check validates the template project including wrangler.toml', async () => {
    const dir = await project();
    const result = cli(['check'], dir);
    assert.equal(result.status, 0, result.stderr);
    assert.match(result.stdout, /wrangler.toml matches the site configuration/);
    assert.match(result.stdout, /Valid site configuration: https:\/\/www.example.com/);
  });
  it('check fails with actionable errors', async () => {
    const dir = await project();
    await writeFile(
      join(dir, 'site.config.mjs'),
      "export default { identity: { name: 'X', productionUrl: 'https://example.com' }, secruity: {} };\n",
    );
    const result = cli(['check'], dir);
    assert.equal(result.status, 1);
    assert.match(result.stderr, /secruity: unknown key \(did you mean "security"\?\)/);
    const missing = cli(['check', '--site', 'nope.mjs'], dir);
    assert.equal(missing.status, 2);
    assert.match(missing.stderr, /Site configuration not found/);
  });
  it('check reports Wrangler drift and refuses ambiguous Wrangler files', async () => {
    const dir = await project();
    const toml = await readFile(join(dir, 'wrangler.toml'), 'utf8');
    await writeFile(
      join(dir, 'wrangler.toml'),
      toml.replace('workers_dev = false', 'workers_dev = true'),
    );
    assert.match(cli(['check'], dir).stderr, /workers_dev must be explicitly false/);
    await writeFile(join(dir, 'wrangler.json'), '{}');
    assert.match(cli(['check'], dir).stderr, /Several Wrangler files found/);
  });
  it('generate-headers writes dist/_headers and refuses to overwrite a copied public/_headers', async () => {
    const dir = await project();
    await mkdir(join(dir, 'dist'));
    await writeFile(join(dir, 'dist/_headers'), '/*\n  X-Custom: 1\n');
    const refused = cli(['generate-headers'], dir);
    assert.equal(refused.status, 1);
    assert.match(refused.stderr, /was not generated by brclz/);
    assert.equal(cli(['generate-headers', '--force'], dir).status, 0);
    assert.match(
      await readFile(join(dir, 'dist/_headers'), 'utf8'),
      /^# Generated by @valentinbrclz\/web-standards/,
    );
    assert.equal(cli(['generate-headers'], dir).status, 0, 'regenerating its own file is allowed');
  });
  it('generate-header-rules writes the Worker rules and --check detects drift', async () => {
    const dir = await project();
    const file = join(dir, '.generated/header-rules.json');
    assert.equal(cli(['generate-header-rules', '--check'], dir).status, 1, 'missing');
    const written = cli(['generate-header-rules'], dir);
    assert.equal(written.status, 0, written.stderr);
    const rules = JSON.parse(await readFile(file, 'utf8'));
    assert.equal(rules[0].pattern, '/*');
    assert.doesNotMatch(await readFile(file, 'utf8'), /"source"/);
    assert.equal(cli(['generate-header-rules', '--check'], dir).status, 0);
    await writeFile(file, '[]\n');
    assert.match(cli(['generate-header-rules', '--check'], dir).stderr, /out of date/);
  });
  it('validate-redirects uses the site trailing-slash policy and --strict', async () => {
    const dir = await project();
    await mkdir(join(dir, 'public'));
    await writeFile(join(dir, 'public/_redirects'), '/old /new/ 301\n');
    const ok = cli(['validate-redirects'], dir);
    assert.equal(ok.status, 0);
    assert.match(ok.stderr, /trailingSlash is "never"/);
    assert.equal(cli(['validate-redirects', '--strict'], dir).status, 1);
    await writeFile(join(dir, 'public/_redirects'), '/a /a\n');
    assert.match(cli(['validate-redirects'], dir).stderr, /redirects to itself/);
  });
  it('generate-wrangler writes a JSON file with paths relative to its location', async () => {
    const dir = await project();
    assert.equal(cli(['generate-wrangler'], dir).status, 0);
    const config = JSON.parse(await readFile(join(dir, '.generated/wrangler.json'), 'utf8'));
    assert.equal(config.assets.directory, '../dist');
    assert.equal(
      cli(['generate-wrangler', '--out', 'wrangler.toml'], dir).status,
      1,
      'never overwrites a project file without --force',
    );
  });
  it('print-config shows the resolved configuration', async () => {
    const dir = await project();
    const config = JSON.parse(cli(['print-config'], dir).stdout);
    assert.equal(config.security.headers['X-Frame-Options'], 'DENY');
    assert.equal(config.identity.previewDomain, 'dev.example.com');
    assert.equal(config.cloudflare.workerName, 'com-example');
    assert.equal(config.identity.language, 'fr-CH');
  });
  it('audit-dist fails on a broken build and explains a missing one', async () => {
    const dir = await project();
    assert.match(cli(['audit-dist'], dir).stderr, /Build output not found/);
    await mkdir(join(dir, 'dist'));
    await writeFile(join(dir, 'dist/index.html'), '<html><title>x</title></html>');
    const result = cli(['audit-dist'], dir);
    assert.equal(result.status, 1);
    assert.match(result.stderr, /SEO audit failed/);
  });
  it('check refuses a second site/trailingSlash/format in astro.config.mjs', async () => {
    const dir = await project();
    const ok = cli(['check'], dir);
    assert.match(ok.stdout, /Astro: astro.config.mjs takes its site settings from site.config.mjs/);
    const path = join(dir, 'astro.config.mjs');
    const text = await readFile(path, 'utf8');
    await writeFile(
      path,
      text.replace('  ...base,\n', "  ...base,\n  site: 'https://other.example',\n"),
    );
    const bad = cli(['check'], dir);
    assert.equal(bad.status, 1);
    assert.match(bad.stderr, /astro.config.mjs repeats settings that site.config.mjs owns/);
    assert.match(bad.stderr, /astro.config.mjs:\d+ sets "site"/);
    assert.match(bad.stderr, /readSiteFile\(\)/);
  });
  it('derives the production origin from site.yaml through site.generated.json', async () => {
    const dir = await project();
    await writeFile(join(dir, 'site.yaml'), 'name: Example\ndomain: www.example.com\n');
    const sync = cli(['sync-site-file'], dir);
    assert.equal(sync.status, 0, sync.stderr);
    assert.match(sync.stdout, /Wrote site.generated.json from site.yaml/);
    const config = await readFile(join(dir, 'site.config.mjs'), 'utf8');
    const module = join(root, 'src/config.mjs'); // absolute path: Node and esbuild both resolve it
    await writeFile(
      join(dir, 'site.config.mjs'),
      `import { httpsOrigin } from '${module}';\nimport file from './site.generated.json' with { type: 'json' };\n` +
        config.replace(/productionUrl: "[^"]*"/, 'productionUrl: httpsOrigin(file.domain)'),
    );
    const ok = cli(['check'], dir);
    assert.equal(ok.status, 0, ok.stderr);
    assert.match(ok.stdout, /Site file: site.generated.json matches site.yaml/);
    assert.match(ok.stdout, /Valid site configuration: https:\/\/www.example.com/);
    await writeFile(join(dir, 'site.yaml'), 'name: Example\ndomain: www.example.org\n');
    const stale = cli(['check'], dir);
    assert.equal(stale.status, 1);
    assert.match(stale.stderr, /site.generated.json is out of date with site.yaml/);
    assert.equal(cli(['sync-site-file', '--check'], dir).status, 1);
    assert.equal(cli(['sync-site-file'], dir).status, 0);
    assert.match(cli(['print-config'], dir).stdout, /"productionUrl": "https:\/\/www.example.org"/);
    // site.config.mjs must stay bundleable for Workers: no node: modules, no file access.
    const esbuild = join(root, 'node_modules/.bin/esbuild');
    const bundle = spawnSync(
      esbuild,
      ['site.config.mjs', '--bundle', '--platform=neutral', '--format=esm', '--log-level=error'],
      { cwd: dir, encoding: 'utf8' },
    );
    assert.equal(bundle.status, 0, bundle.stderr);
    assert.doesNotMatch(bundle.stdout, /node:/);
    assert.match(bundle.stdout, /www\.example\.org/);
  });
  it('install-claude installs namespaced files and never overwrites project instructions', async () => {
    const dir = await project();
    await writeFile(join(dir, 'CLAUDE.md'), '# Project rules\n');
    const first = cli(['install-claude'], dir);
    assert.equal(first.status, 0, first.stderr);
    assert.equal(await readFile(join(dir, 'CLAUDE.md'), 'utf8'), '# Project rules\n');
    assert.match(
      await readFile(join(dir, '.claude/rules/web-standards/web-standards.md'), 'utf8'),
      /Web standards/,
    );
    const rules = '.claude/rules/web-standards';
    const general = await readFile(join(dir, rules, 'general.md'), 'utf8');
    assert.match(general, /This codebase is yours/);
    assert.match(general, /Conventional Commits/);
    assert.match(
      general,
      /Que faire\u00a0\?.*\n.*«\u00a0texte\u00a0»/s,
      'the rule shows its own NBSP',
    );
    assert.match(general, /modern-web-guidance@latest search/);
    const ui = await readFile(join(dir, rules, 'ui.md'), 'utf8');
    assert.match(ui, /modern-web-guidance@latest retrieve/);
    assert.match(ui, /^20\. Animate useful feedback$/m);
    for (const old of ['ownership', 'commits', 'french-typography', 'modern-web', 'ui-audit'])
      await assert.rejects(readFile(join(dir, rules, `${old}.md`), 'utf8'), /ENOENT/);
    // The installed AGENTS.md carries the same text as general.md (generated block).
    const agents = await readFile(join(dir, 'AGENTS.md'), 'utf8');
    assert.ok(agents.includes(general.slice(general.indexOf('\n## ')).trim()));
    assert.match(
      await readFile(join(dir, '.claude/skills/standards-check/SKILL.md'), 'utf8'),
      /name: standards-check/,
    );
    assert.ok(
      JSON.parse(
        await readFile(join(dir, '.claude/settings.json'), 'utf8'),
      ).permissions.deny.includes('Read(./.env)'),
    );
    await writeFile(join(dir, '.claude/settings.json'), '{"custom":true}');
    const second = cli(['install-claude'], dir);
    assert.match(second.stdout, /= \.claude\/settings.json/);
    assert.equal(await readFile(join(dir, '.claude/settings.json'), 'utf8'), '{"custom":true}');
    cli(['install-claude', '--force'], dir);
    assert.notEqual(await readFile(join(dir, '.claude/settings.json'), 'utf8'), '{"custom":true}');
    assert.equal(
      await readFile(join(dir, 'CLAUDE.md'), 'utf8'),
      '# Project rules\n',
      '--force never touches CLAUDE.md',
    );
  });

  it('init creates a valid project with derived defaults and only the selected features', async () => {
    const dir = await project('--features', 'search,typography', '--language', 'en');
    const pkg = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8'));
    assert.equal(pkg.name, 'com-example');
    assert.equal(
      pkg.scripts.build,
      'astro build && pagefind --site dist && brclz generate-headers',
    );
    assert.ok(pkg.devDependencies.pagefind && pkg.devDependencies['@tailwindcss/typography']);
    assert.ok(
      pkg.dependencies.astro &&
        pkg.dependencies['@astrojs/sitemap'] &&
        pkg.devDependencies['@axe-core/playwright'],
    );
    assert.equal(pkg.dependencies['posthog-js'], undefined);
    assert.match(
      pkg.devDependencies['@valentinbrclz/web-standards'],
      /^github:ValentinBrclz\/brclz-web-standards$/,
    );
    assert.match(
      await readFile(join(dir, 'src/styles/global.css'), 'utf8'),
      /@tailwindcss\/typography/,
    );
    assert.match(await readFile(join(dir, '.gitignore'), 'utf8'), /node_modules/);
    assert.doesNotMatch(
      await readFile(join(dir, 'src/layouts/BaseLayout.astro'), 'utf8'),
      /Analytics/,
    );
    await assert.rejects(readFile(join(dir, 'src/scripts/analytics.ts')));
    await readFile(join(dir, 'src/pages/search.astro'));
    const check = cli(['check', '--strict'], dir);
    assert.equal(check.status, 0, check.stderr + check.stdout);
    assert.match(check.stdout, /wrangler.toml matches the site configuration/);
    const config = JSON.parse(cli(['print-config'], dir).stdout);
    assert.deepEqual(config.security.csp['script-src'], ["'self'", "'wasm-unsafe-eval'"]);
    assert.equal(config.identity.language, 'en');
  });
  it('init refuses bad input and non-empty directories, leaving nothing behind', async () => {
    const parent = await mkdtemp(join(tmpdir(), 'ws-cli-'));
    dirs.push(parent);
    assert.equal(cli(['init', 'x', '--name', 'X'], parent).status, 2);
    assert.match(
      cli(['init', 'x', '--name', 'X', '--url', 'https://x.test', '--features', 'nope'], parent)
        .stderr,
      /Unknown feature\(s\): nope/,
    );
    assert.match(
      cli(['init', 'x', '--name', 'X', '--url', 'http://x.test'], parent).stderr,
      /productionUrl/,
    );
    await assert.rejects(readFile(join(parent, 'x/package.json')));
    await mkdir(join(parent, 'busy'));
    await writeFile(join(parent, 'busy/file'), 'x');
    assert.match(
      cli(['init', 'busy', '--name', 'X', '--url', 'https://x.test'], parent).stderr,
      /is not empty/,
    );
  });
});
